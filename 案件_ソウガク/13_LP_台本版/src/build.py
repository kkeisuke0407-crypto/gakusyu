    """テンプレート中の <!--SLOT:IMG-xx--> を、画像（gen_map.json にあるもの）か画像指示枠に置き換える"""
    used = re.findall(r"<!--SLOT:(IMG-\d+)-->", t)
    assert set(used) <= set(SLOTS), used
    for k, d in SLOTS.items():
        t = t.replace(f"<!--SLOT:{k}-->", slot(k, d))
    return t

