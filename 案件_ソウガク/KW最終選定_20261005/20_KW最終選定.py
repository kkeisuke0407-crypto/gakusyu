    s = j(r['keyword'])
    pf = r['portfolio']
    if r['判定'] == 'EXCLUDE':
        if '語義' in r['理由'] and (TRAIT_CORE.search(s) or TRAIT_SUB.search(s)) or 'ディズレクシア' in s:
            return 'R01', 'REVIEW', '10/05除外から戻す（特性の語義・表記揺れ。情報収集だけを理由に除外しない）'
        return None, '除外', '10/05除外：' + r['理由']
    for pat, why in NEW_EXCLUDE:
        if pat.search(s):
            return None, '除外', why
    if r['判定'] == 'REVIEW':
        return 'R03', 'REVIEW', '10/05のREVIEW：' + r['理由']
    trait_core = bool(TRAIT_CORE.search(s))
    trait = trait_core or bool(TRAIT_SUB.search(s))
    fut = bool(FUTOUKOU.search(s))
    svc = bool(SERVICE.search(s))
    # ③ 競合
    if pf.startswith('③'):
        if REVIEW_CONTENT.search(s) and not (trait or fut or SWITCH.search(s) or PRICE.search(s)):
            return 'R04', 'REVIEW', '競合名×コンテンツ視聴語'
        if trait or fut:
            return 'N20', '採用', ''
        if pf.startswith('③X'):
            return 'N21', '採用', ''
        if SWITCH.search(s):
            return 'N19', '採用', ''
        if pf.startswith('③A'):
            if CHOICE.search(s) or PRICE.search(s) or TRIAL.search(s):
                return 'N14', '採用', ''
            return 'N15', '採用', ''
        if PRICE.search(s):
            return 'N17', '採用', ''
